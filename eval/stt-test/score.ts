/**
 * STT verbatim test scorer (voice-plan §6). Reads sentences + results/*.json, writes results.md.
 * Usage (repo root):
 *   npx tsx eval/stt-test/score.ts [--sentences eval/sentences.json] [--results eval/stt-test/results] [--out eval/stt-test/results.md]
 * Normalisation happens here only, for scoring. The data and the transcripts in the report stay raw.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

export type Sentence = {
  id: string;
  text: string;
  error_span: string | null;
  corrected_span: string | null;
  error_type: string | null;
};
export type ResultRow = {
  pass: string;
  reader: string;
  id: string;
  config: string;
  transcript: string;
  ms: number;
  error?: string;
};
export type Verdict = "survived" | "fixed" | "garbled" | "clean_kept" | "clean_changed" | "call_error";

/** Lowercase, strip accents and punctuation, collapse spaces. For scoring only. */
export function normalise(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

/** Whole-word containment on normalised text. */
function has(transcript: string, span: string): boolean {
  return ` ${normalise(transcript)} `.includes(` ${normalise(span)} `);
}

export function scoreRow(sentence: Sentence, row: ResultRow): Verdict {
  if (row.error) return "call_error";
  if (sentence.error_span === null) {
    return normalise(row.transcript) === normalise(sentence.text) ? "clean_kept" : "clean_changed";
  }
  if (has(row.transcript, sentence.error_span)) return "survived";
  if (sentence.corrected_span !== null && has(row.transcript, sentence.corrected_span)) return "fixed";
  return "garbled";
}

type Counts = Record<Verdict, number>;
const emptyCounts = (): Counts => ({
  survived: 0,
  fixed: 0,
  garbled: 0,
  clean_kept: 0,
  clean_changed: 0,
  call_error: 0,
});

export type ScoreSummary = {
  /** Key: `${pass}|${config}` (all readers together). */
  byPassConfig: Record<string, Counts>;
  /** Key: `${pass}|${reader}|${config}`. */
  byReader: Record<string, Counts>;
  /** Key: `${pass}|${config}|${error_type}`. */
  byType: Record<string, Counts>;
  /** Key: `${pass}|${config}`; rows with a call error are left out. */
  medianMs: Record<string, number>;
  /** Result rows whose id is not in the sentences file. */
  unknownIds: string[];
  markdown: string;
};

function median(xs: number[]): number {
  if (xs.length === 0) return NaN;
  const s = [...xs].sort((a, b) => a - b);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
}

const pct = (n: number, d: number) => (d === 0 ? "n/a" : `${Math.round((100 * n) / d)}% (${n}/${d})`);
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ");
const bump = (map: Record<string, Counts>, key: string, v: Verdict) => {
  (map[key] ??= emptyCounts())[v]++;
};

export function score(args: { sentences: string; resultsDir: string; out: string }): ScoreSummary {
  const sentences = JSON.parse(readFileSync(args.sentences, "utf8")) as Sentence[];
  const byId = new Map(sentences.map((s) => [s.id, s]));
  const rows: ResultRow[] = [];
  for (const f of readdirSync(args.resultsDir).sort()) {
    if (!f.endsWith(".json")) continue;
    rows.push(...(JSON.parse(readFileSync(path.join(args.resultsDir, f), "utf8")) as ResultRow[]));
  }

  const byPassConfig: Record<string, Counts> = {};
  const byReader: Record<string, Counts> = {};
  const byType: Record<string, Counts> = {};
  const msByKey: Record<string, number[]> = {};
  const unknownIds: string[] = [];
  const scored: { row: ResultRow; sentence: Sentence; verdict: Verdict }[] = [];

  for (const row of rows) {
    const sentence = byId.get(row.id);
    if (!sentence) {
      if (!unknownIds.includes(row.id)) unknownIds.push(row.id);
      continue;
    }
    const verdict = scoreRow(sentence, row);
    scored.push({ row, sentence, verdict });
    const pc = `${row.pass}|${row.config}`;
    bump(byPassConfig, pc, verdict);
    bump(byReader, `${row.pass}|${row.reader}|${row.config}`, verdict);
    if (sentence.error_type) bump(byType, `${pc}|${sentence.error_type}`, verdict);
    if (!row.error) (msByKey[pc] ??= []).push(row.ms);
  }

  const medianMs: Record<string, number> = {};
  for (const [k, v] of Object.entries(msByKey)) medianMs[k] = median(v);

  // Survival denominators leave out controls and failed calls.
  const planted = (c: Counts) => c.survived + c.fixed + c.garbled;
  const controls = (c: Counts) => c.clean_kept + c.clean_changed;

  const md: string[] = [];
  md.push("# STT verbatim test results", "");
  md.push(
    `Generated by \`eval/stt-test/score.ts\` from ${rows.length} result rows and ${sentences.length} sentences. ` +
      "Scoring normalises (lowercase, no accents or punctuation); the transcripts below are raw.",
    "",
    "- **survived**: the planted `error_span` is in the transcript (what we want).",
    "- **fixed**: the `corrected_span` is there and the error is not (STT rewrote the learner).",
    "- **garbled**: neither. Counted as not survived; read these by eye.",
    "- `rt:` ms is commit to final transcript; `batch:` ms is the whole request.",
    "",
  );
  if (unknownIds.length) md.push(`**Skipped rows with ids not in the sentences file:** ${unknownIds.join(", ")}`, "");

  md.push("## Survival per configuration per pass", "");
  md.push("| Pass | Config | Survived | Fixed | Garbled | Controls kept clean | Call errors | Median ms |");
  md.push("|---|---|---|---|---|---|---|---|");
  for (const key of Object.keys(byPassConfig).sort()) {
    const [pass, config] = key.split("|");
    const c = byPassConfig[key];
    const m = medianMs[key];
    md.push(
      `| ${pass} | ${config} | ${pct(c.survived, planted(c))} | ${c.fixed} | ${c.garbled} | ` +
        `${pct(c.clean_kept, controls(c))} | ${c.call_error} | ${m === undefined ? "n/a" : Math.round(m)} |`,
    );
  }
  md.push("");

  const readerKeys = Object.keys(byReader)
    .filter((k) => k.startsWith("B|"))
    .sort();
  if (readerKeys.length) {
    md.push("## Pass B per reader", "");
    md.push("| Reader | Config | Survived | Fixed | Garbled | Controls kept clean | Call errors |");
    md.push("|---|---|---|---|---|---|---|");
    for (const key of readerKeys) {
      const [, reader, config] = key.split("|");
      const c = byReader[key];
      md.push(
        `| ${reader} | ${config} | ${pct(c.survived, planted(c))} | ${c.fixed} | ${c.garbled} | ` +
          `${pct(c.clean_kept, controls(c))} | ${c.call_error} |`,
      );
    }
    md.push("");
  }

  md.push("## Survival per error type", "");
  md.push("| Pass | Config | Error type | Survived | Fixed | Garbled |");
  md.push("|---|---|---|---|---|---|");
  for (const key of Object.keys(byType).sort()) {
    const [pass, config, type] = key.split("|");
    const c = byType[key];
    md.push(`| ${pass} | ${config} | ${type} | ${pct(c.survived, planted(c))} | ${c.fixed} | ${c.garbled} |`);
  }
  md.push("");

  md.push("## Per sentence", "");
  md.push("| Id | Pass | Reader | Config | Verdict | ms | Error span | Raw transcript |");
  md.push("|---|---|---|---|---|---|---|---|");
  const order = new Map(sentences.map((s, i) => [s.id, i]));
  scored.sort(
    (a, b) =>
      order.get(a.row.id)! - order.get(b.row.id)! ||
      a.row.pass.localeCompare(b.row.pass) ||
      a.row.reader.localeCompare(b.row.reader) ||
      a.row.config.localeCompare(b.row.config),
  );
  for (const { row, sentence, verdict } of scored) {
    const shown = row.error ? `ERROR: ${row.error}` : row.transcript;
    md.push(
      `| ${row.id} | ${row.pass} | ${row.reader} | ${row.config} | ${verdict} | ${Math.round(row.ms)} | ` +
        `${cell(sentence.error_span ?? "(control)")} | ${cell(shown)} |`,
    );
  }
  md.push("");

  const markdown = md.join("\n");
  writeFileSync(args.out, markdown);
  return { byPassConfig, byReader, byType, medianMs, unknownIds, markdown };
}

function flag(argv: string[], name: string, fallback: string): string {
  const i = argv.indexOf(name);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : fallback;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const argv = process.argv.slice(2);
  const out = flag(argv, "--out", "eval/stt-test/results.md");
  const summary = score({
    sentences: flag(argv, "--sentences", "eval/sentences.json"),
    resultsDir: flag(argv, "--results", "eval/stt-test/results"),
    out,
  });
  for (const key of Object.keys(summary.byPassConfig).sort()) {
    const c = summary.byPassConfig[key];
    console.log(
      `${key}: survived ${c.survived}, fixed ${c.fixed}, garbled ${c.garbled}, ` +
        `controls kept ${c.clean_kept}/${c.clean_kept + c.clean_changed}, call errors ${c.call_error}`,
    );
  }
  console.log(`wrote ${out}`);
}
