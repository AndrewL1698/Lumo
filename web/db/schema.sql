-- Lumo DB schema (architecture §5). Idempotent: paste into the Supabase SQL editor; safe to re-run.
-- Single demo user: user_id = DEMO_USER_ID, no users table, no RLS (service key only, server side).

create extension if not exists pgcrypto; -- gen_random_uuid()

-- Word list, seeded by scripts/build-wordlist. band: 1 = Beginner, 2 = Intermediate, 3 = Upper-intermediate.
create table if not exists words (
  lemma         text primary key,
  rank          int not null,
  pos           text not null check (pos in ('noun', 'verb', 'adj', 'adv')),
  gender        text check (gender in ('m', 'f')),          -- nouns only
  article       text,                                       -- nouns only, singular definite ("el agua")
  english       text[] not null,
  english_forms text[] not null,
  cognate       boolean not null default false,
  false_friend  boolean not null default false,
  band          smallint not null check (band between 1 and 3)
);
create index if not exists words_band_rank_idx on words (band, rank);

create table if not exists user_words (
  user_id       uuid not null,
  lemma         text not null references words (lemma),
  state         text not null default 'new'
                check (state in ('new', 'seen', 'learning', 'known', 'mastered', 'known_assumed')),
  fsrs_card     jsonb,
  seen_count    int not null default 0,
  seen_articles text[] not null default '{}',
  last_hover_at timestamptz,
  due_at        timestamptz,
  primary key (user_id, lemma)
);
create index if not exists user_words_due_idx on user_words (user_id, due_at);

-- id is generated by the extension, so retried batches are idempotent (insert ... on conflict do nothing).
create table if not exists events (
  id          uuid primary key,
  user_id     uuid not null,
  type        text not null,
  lemma       text,          -- no FK: events may reference words outside the list
  article_key text,          -- hash(domain + title); URLs are never stored
  ts          timestamptz not null,
  meta        jsonb
);
create index if not exists events_user_ts_idx on events (user_id, ts);

create table if not exists articles (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null,
  article_key text not null,
  title       text,
  domain      text,
  ts          timestamptz not null default now(),
  unique (user_id, article_key)
);

create table if not exists tutor_sessions (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null,
  started_at timestamptz not null default now(),
  ended_at   timestamptz,
  recap      jsonb
);

-- raw_text = verbatim STT output, the only thing ever graded. display_text is kept separately.
create table if not exists utterances (
  id           uuid primary key default gen_random_uuid(),
  session_id   uuid not null references tutor_sessions (id) on delete cascade,
  raw_text     text not null,
  display_text text,
  correction   jsonb,
  ts           timestamptz not null default now()
);

create table if not exists pair_codes (
  code       text primary key,
  token      text not null,
  expires_at timestamptz
);

create table if not exists settings (
  user_id uuid primary key,
  data    jsonb not null default '{}'
);
