/**
 * articleKey = SHA-256 hex of `hostname\ntitle` (agreed with Karthik so live hovers join the
 * seeded article). URLs and page text are never sent (specs §5.1).
 */
async function computeArticleKey(): Promise<string> {
  const input = `${location.hostname}\n${document.title}`;
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(input));
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

function newEvent(type: ExtensionEvent["type"], extra: Partial<ExtensionEvent> = {}): ExtensionEvent {
  return { id: crypto.randomUUID(), type, articleKey, ts: Date.now(), ...extra };
}

function queue(...events: ExtensionEvent[]): void {
  void send({ type: "QUEUE_EVENTS", events }).catch(() => {
    /* the SW keeps its own queue; losing one message is not worth surfacing on the page */
  });
}

// ---------------------------------------------------------------- walking

function isVisible(element: Element): boolean {
  return element.checkVisibility({ checkOpacity: true, checkVisibilityCSS: true });
}

function collectTextNodes(root: Node): Text[] {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node: Node): number {
      const text = node.nodeValue;
      if (!text || text.trim().length < 12) return NodeFilter.FILTER_REJECT;
      const parent = (node as Text).parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      if (parent.closest(SKIP_SELECTOR)) return NodeFilter.FILTER_REJECT;
      if (!isVisible(parent)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const nodes: Text[] = [];
  let current = walker.nextNode();
  while (current) {
    nodes.push(current as Text);
    current = walker.nextNode();
  }
  return nodes;
}

/** Index of the sentence `offset` falls in, within one text node. */
function sentenceIndexAt(text: string, offset: number): number {
  let index = 0;
  for (let i = 0; i < offset && i < text.length; i++) {
    if ((text[i] === "." || text[i] === "!" || text[i] === "?") && /\s/.test(text[i + 1] ?? " ")) {
      index++;
    }
  }
  return index;
}

/** The sentence around `offset`, taken from the containing block so Claude gets real context. */
function sentenceAround(node: Text, offset: number): string {
  const block = node.parentElement?.closest("p, li, h1, h2, h3, blockquote") ?? node.parentElement;
  const full = (block?.textContent ?? node.nodeValue ?? "").replace(/\s+/g, " ").trim();
  const needle = (node.nodeValue ?? "").slice(Math.max(0, offset - 20), offset + 40).trim();
  const at = needle ? full.indexOf(needle.split(/\s+/)[0] ?? "") : -1;
  const pivot = at < 0 ? 0 : at;
  let start = full.lastIndexOf(".", pivot);
  start = start < 0 ? 0 : start + 1;
  let end = full.indexOf(".", pivot);
  end = end < 0 ? full.length : end + 1;
  const sentence = full.slice(start, end).trim();
  return sentence.length > 20 ? sentence.slice(0, 400) : full.slice(0, 400);
}

// ---------------------------------------------------------------- matching and scoring

/** How brightly a swap glows = how well the learner knows it (same three lights as the web app, D-016). */
type Glow = "seen" | "learning" | "steady" | "known";
function glowOf(state: string | undefined): Glow {
  if (state === "learning") return "learning";
  if (state === "known" || state === "mastered") return "known";
  // Never met, only seen on a page, or known_assumed (placement guess, swapped at steps 1+): solid needs proof.
  return "seen";
}

/** "Knew it" words glow steady: learning's look without the flicker. Proven-known stays solid (D-018). */
function glowFor(lemma: string, state: string | undefined): Glow {
  const glow = glowOf(state);
  return glow !== "known" && knewIt.has(lemma) ? "steady" : glow;
}

interface Match {
  glow: Glow;
  node: Text;
  /** The token's index within its text node (when matched). */
  offset: number;
  englishMatch: string;
  lemma: string;
  sentence: string;
  wordIndex: number;
  sentenceKey: string;
  isReview: boolean;
  score: number;
}

/** Never-met words easier than the learner's level are assumed known (specs §4): never swapped. */
const SKIP = -Infinity;

/**
 * Variety without randomness: a stable 0..1 value per (article, lemma). Different articles still vary, but a reload
 * of the same page picks the same words, so every translation is already cached and swaps appear almost instantly.
 */
function steadyRandom(lemma: string): number {
  let h = 2166136261;
  for (const ch of articleKey + "|" + lemma) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return (h >>> 0) / 4294967296;
}

/** specs §5.2.5, plus a little per-article jitter so the same words don't win on every page. */
function scoreOf(c: Candidate | undefined, lemma: string): number {
  const jitter = steadyRandom(lemma) * 0.4;
  if (!c) {
    // Never met: match the learner's level (D-007). Easier = assumed known, harder = only if nothing better.
    const band = BANDS[lemma] ?? userBand;
    // Immersion steps 1+ (D-018) include easier words too, below the learner's own band.
    if (band < userBand) return rules.includeEasy ? 0.5 + jitter : SKIP;
    return band === userBand ? 1.0 + jitter : 0.2 + jitter * 0.25;
  }
  if (c.state === "known_assumed") return rules.includeEasy ? 0.5 + jitter : SKIP;
  return (
    (c.isDue ? 3.0 : 0) +
    (c.hoveredRecently ? 2.0 : 0) +
    (c.onWeakList ? 1.5 : 0) +
    (c.isNewInBand ? 1.0 : 0) +
    (c.isMastered ? -5.0 : 0) +
    jitter
  );
}

function findMatches(nodes: Text[], byLemma: Map<string, Candidate>): Match[] {
  const found: Match[] = [];
  let wordsWalked = 0;

  for (const node of nodes) {
    const text = node.nodeValue ?? "";
    const nodeStart = wordsWalked;
    let wordInNode = 0;

    for (const m of text.matchAll(/[A-Za-z][A-Za-z'’-]*/g)) {
      wordInNode++;
      const token = m[0];
      const lemmas = FORMS[token.toLowerCase()];
      if (!lemmas?.length) continue;
      // Proper nouns mid-sentence are names, not vocabulary.
      if (m.index > 0 && /^[A-Z]/.test(token) && !/[.!?]\s+$/.test(text.slice(0, m.index))) continue;

      const lemma = lemmas
        .map((l) => ({ l, s: scoreOf(byLemma.get(l), l) }))
        .sort((a, b) => b.s - a.s)[0];
      if (!lemma || lemma.s === SKIP) continue;

      const state = byLemma.get(lemma.l)?.state;
      found.push({
        node,
        offset: m.index,
        englishMatch: token,
        lemma: lemma.l,
        sentence: sentenceAround(node, m.index),
        wordIndex: nodeStart + wordInNode,
        sentenceKey: `${nodeStart}:${sentenceIndexAt(text, m.index)}`,
        // known_assumed (only swapped at steps 1+) is a placement guess: fresh, so it never crowds the review slice.
        isReview: Boolean(state && state !== "new" && state !== "known_assumed"),
        score: lemma.s,
        glow: glowFor(lemma.l, state),
      });
    }
    wordsWalked += wordInNode;
  }
  return found;
}

/**
 * Score-first greedy pick (every step, D-018): best review words until the 70/30 share is met, then every fresh word,
 * then review again to top up. A match is skipped if its lemma is already used on the page, its sentence already has
 * rules.perSentence picks, or it sits within minGap words of a pick. Word indices restart at 0 every sweep (each sweep
 * only sees new text nodes), so the gap starts fresh each sweep. Returned in priority order (best first), so the
 * caller can over-pick and keep the best ones that translate.
 */
function pickWords(matches: Match[], budget: number): Match[] {
  const review = matches.filter((m) => m.isReview).sort((a, b) => b.score - a.score);
  const fresh = matches.filter((m) => !m.isReview).sort((a, b) => b.score - a.score);
  const want = Math.round(budget * REVIEW_SHARE);

  const chosen: Match[] = [];
  const usedLemmas = new Set<string>(swappedLemmas);
  const perSentence = new Map<string, number>();
  const add = (m: Match): void => {
    if (chosen.length >= budget) return;
    if (usedLemmas.has(m.lemma)) return; // one swap per lemma per page
    const inSentence = perSentence.get(m.sentenceKey) ?? 0;
    if (inSentence >= rules.perSentence) return;
    if (chosen.some((c) => Math.abs(c.wordIndex - m.wordIndex) < minGap)) return;
    chosen.push(m);
    usedLemmas.add(m.lemma);
    perSentence.set(m.sentenceKey, inSentence + 1);
  };

  for (const m of review) {
    if (chosen.length >= want) break;
    add(m);
  }
  for (const m of fresh) add(m);
  for (const m of review) add(m); // top up if fresh ran out
  return chosen;
}

