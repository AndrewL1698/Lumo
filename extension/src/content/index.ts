/**
 * Complete sentences in one text node's text, as [start, end) ranges. A terminator only ends a sentence when the
 * token before it isn't a single letter ("J."), a dotted capital abbreviation ("U.S.") or a listed abbreviation, and
 * the next non-space character is uppercase, a digit or an opening quote. The node's first sentence counts only if
 * nothing precedes the node in its element (`openStart`), its last unterminated one only if nothing follows it.
 */
function sentenceBounds(text: string, openStart: boolean, openEnd: boolean): [number, number][] {
  const bounds: [number, number][] = [];
  let from = 0;
  for (const t of text.matchAll(/[.!?]+(?=\s|$)/g)) {
    const to = t.index + t[0].length;
    if (/^\.+$/.test(t[0])) {
      const before = (/(\S*)$/.exec(text.slice(0, t.index))?.[1] ?? "").replace(/^[^A-Za-z0-9]+/, "");
      if (/^[A-Za-z]$/.test(before) || /^([A-Z]\.)+[A-Z]$/.test(before) || ABBREVIATIONS.has(before.toLowerCase())) continue;
    }
    const next = /\S/.exec(text.slice(to))?.[0];
    if (next && !/[A-Z0-9“"‘'(]/.test(next)) continue;
    if (from > 0 || openStart) bounds.push([from, to]);
    from = to;
  }
  if (from < text.length && (from > 0 || openStart) && openEnd) bounds.push([from, text.length]);
  return bounds;
}

function quotesBalanced(s: string): boolean {
  const count = (ch: string) => s.split(ch).length - 1;
  return count("“") === count("”") && count('"') % 2 === 0;
}

function blockOp(b: Block, spanish: string): SwapOp {
  const el = document.createElement("span");
  el.setAttribute(BLOCK_ATTR, "");
  el.dataset.parrotEn = b.english;
  el.textContent = spanish;
  return {
    node: b.node,
    start: b.start,
    end: b.end,
    expect: b.raw,
    el,
    rank: 1, // a block wins over any word swap inside it
    onApplied() {
      /* counted when picked (pickBlocks); blocks send no events */
    },
  };
}

/** Every immersion step (D-018): many swaps per text node, placed by offset. Step 0 is just its rules (no blocks). */
async function sweep(root: Node): Promise<void> {
  const blocksLeft =
    sentenceBlocksDone < rules.sentenceBlocks || paragraphBlocksDone < rules.paragraphBlocks;
  if (swapCount >= pageCap && !blocksLeft) return;

  const nodes = collectTextNodes(root).filter((n) => !seenNodes.has(n));
  for (const n of nodes) seenNodes.add(n);
  if (!nodes.length) return;

  const candidates = await send({ type: "GET_CANDIDATES" }).catch(() => null);
  const byLemma = new Map((candidates?.candidates ?? []).map((c) => [c.lemma, c]));

  // Blocks are reserved before word picking: paragraph nodes leave the word pass, and words inside a chosen
  // sentence are not picked.
  const blocks = blocksLeft ? pickBlocks(nodes, byLemma) : [];
  const paragraphNodes = new Set(blocks.filter((b) => b.kind === "paragraph").map((b) => b.node));
  const sentenceRanges = new Map(blocks.filter((b) => b.kind === "sentence").map((b) => [b.node, b]));
  const matches = findMatches(
    nodes.filter((n) => !paragraphNodes.has(n)),
    byLemma,
  ).filter((m) => {
    const r = sentenceRanges.get(m.node);
    return !r || m.offset + m.englishMatch.length <= r.start || m.offset >= r.end;
  });
  const chosen = pickWords(matches, Math.ceil(Math.max(0, pageCap - swapCount) * OVERPICK));
  if (!chosen.length && !blocks.length) {
    console.log(`[parrot] step ${rules.step}: ${nodes.length} new text node(s), nothing worth swapping`);
    return;
  }

  // The original text of every node, before either batch splits anything: word spans are located against it.
  const original = new Map(nodes.map((n) => [n, n.data]));

  // ONE word batch and ONE sentence batch, sent together, each applied as soon as it returns: slow sentence
  // calls never hold up the words. Load is never blocked.
  const words = chosen.length
    ? send({
        type: "TRANSLATE",
        articleKey,
        items: chosen.map((m) => ({ sentence: m.sentence, lemma: m.lemma, englishMatch: m.englishMatch })),
      })
        .catch(() => null)
        .then((res) => {
          if (!res) return console.log("[parrot] translate unavailable, no word swaps this time");
          const ops: SwapOp[] = [];
          res.items.forEach((item, i) => {
            const m = chosen[i];
            if (!item || !m) return; // null = sense mismatch, don't swap
            if (swappedLemmas.has(m.lemma)) return; // another sweep swapped it while this batch was out
            const start = locateSpan(m, item.span, original.get(m.node));
            if (start < 0) return; // span not in this node (crosses an inline element): skip rather than guess
            // A span the server widened ("the ...") must not reach into a reserved sentence.
            const r = sentenceRanges.get(m.node);
            if (r && start < r.end && start + item.span.length > r.start) return;
            ops.push(wordOp(m, start, item.span, item.replacement));
          });
          // Ops are in pick priority (best first): keep the best that translated, up to what's left of the budget
          // (a parallel sweep may have used some).
          ops.splice(Math.max(0, pageCap - swapCount));
          const applied = applyOps(ops);
          console.log(
            `[parrot] step ${rules.step}: swapped ${applied} of ${chosen.length} chosen ` +
              `(page total ${swapCount}), ≤${rules.perSentence} per sentence`,
          );
        })
    : null;

  const sentencesDone = blocks.length
    ? send({ type: "TRANSLATE_SENTENCES", articleKey, sentences: blocks.map((b) => b.english) })
        .catch(() => null)
        .then((res) => {
          if (!res) return console.log("[parrot] sentence translate unavailable, no blocks this time");
          const ops: SwapOp[] = [];
          res.items.forEach((spanish, i) => {
            const b = blocks[i];
            if (spanish && b) ops.push(blockOp(b, spanish)); // null = leave that text English
          });
          const applied = applyOps(ops);
          const sentences = ops.filter((op) => op.el.isConnected && !paragraphNodes.has(op.node)).length;
          console.log(
            `[parrot] blocks: ${sentences} sentences + ${applied - sentences} paragraphs applied of ${blocks.length} chosen`,
          );
        })
    : null;

  await Promise.all([words, sentencesDone]);
}

// ---------------------------------------------------------------- observers

let timer: ReturnType<typeof setTimeout> | undefined;
function watchForNewText(): void {
  const observer = new MutationObserver((records) => {
    if (swapCount >= pageCap) {
      observer.disconnect();
      return;
    }
    const roots = records
      .flatMap((r) => [...r.addedNodes])
      .filter((n) => n.nodeType === Node.ELEMENT_NODE || n.nodeType === Node.TEXT_NODE);
    if (!roots.length) return;

    clearTimeout(timer);
    timer = setTimeout(() => {
      if (neverListReason(location.href)) {
        observer.disconnect();
        return;
      }
      for (const root of roots) if (root.isConnected) void sweep(root);
    }, DEBOUNCE_MS);
  });
  observer.observe(document.body, { childList: true, subtree: true });
}

function wireHoverCard(): void {
  installHoverCard(MARK_ATTR, {
    onHover(t: HoverTarget) {
      queue(newEvent("hover", { lemma: t.lemma, meta: { sentence: t.sentence } }));
      // A look-up makes the word "learning" (learner model), so it starts to flicker right away.
      for (const el of document.querySelectorAll<HTMLElement>(`[${MARK_ATTR}]`)) {
        if (el.dataset.parrotLemma === t.lemma && el.dataset.parrotGlow === "seen") el.dataset.parrotGlow = "learning";
      }
    },
    onVerdict(t: HoverTarget, verdict) {
      queue(newEvent(verdict, { lemma: t.lemma, meta: { sentence: t.sentence } }));
      // D-018, display only: Knew it = steady (no flicker), Didn't know = flicker. Solid stays for proven-known.
      if (verdict === "knew_it") knewIt.add(t.lemma);
      else knewIt.delete(t.lemma);
      for (const el of document.querySelectorAll<HTMLElement>(`[${MARK_ATTR}]`)) {
        if (el.dataset.parrotLemma !== t.lemma || el.dataset.parrotGlow === "known") continue;
        el.dataset.parrotGlow = verdict === "knew_it" ? "steady" : "learning";
      }
    },
    /** The service worker fetches and caches the audio; we only play it. */
    async onSpeak(t: HoverTarget) {
      const res = await send({ type: "TTS", text: t.spanish, lemma: t.lemma }).catch(() => null);
      if (!res) return false;
      try {
        await new Audio(res.dataUrl).play();
        return true;
      } catch (err) {
        // Some pages' CSP blocks media from a data: URL.
        // TODO(naren): fall back to an offscreen document if a demo site does this.
        console.warn("[parrot] could not play pronunciation here", err);
        return false;
      }
    },
  });
}

/** Swap amount (popup slider or "Grow automatically") and the learner's level, from Settings + progress. */
async function loadBudget(): Promise<void> {
  const [s, c] = await Promise.all([
    send({ type: "GET_SETTINGS" }).catch(() => null),
    send({ type: "GET_CANDIDATES" }).catch(() => null),
  ]);
  if (!s) return; // service worker unreachable: keep the defaults
  // An older service worker sends no immersion: that's step 0, today's behaviour.
  const immersion = s.immersion ?? { points: 0, rate: 1, percent: 0 };
  rules = pageRules(s.settings, s.autoGrow, immersion, c?.candidates ?? []);
  pageCap = rules.words;
  userBand = LEVEL_BAND[s.settings.level] ?? 2;
  minGap = rules.step === 0 ? Math.max(4, Math.round((MIN_WORD_GAP * 10) / Math.max(10, pageCap))) : rules.minGap;
  for (const lemma of s.knewIt ?? []) knewIt.add(lemma);
  console.log(
    `[parrot] step ${rules.step}, immersion ${immersion.percent}%, budget ${pageCap} swaps ` +
      `(${s.autoGrow ? "auto" : "slider"}), ≤${rules.perSentence} per sentence, gap ${minGap}, level ${s.settings.level}`,
  );
}

/**
 * Keep the ambience layer in step with the on/off switch while the page stays open: the popup and
 * the web app both write Settings through chrome.storage.local, so a change there is the signal.
 * Only the layer reacts — swaps already on the page stay put, and new swaps need a reload.
 */
function watchLuciSwitch(): void {
  try {
    chrome.storage.onChanged.addListener((changes, area) => {
      if (area !== "local" || (!changes.settings && !changes.autoGrow)) return;
      void loadBudget()
        .then(() => (pageCap === 0 ? hideAmbience() : showAmbience()))
        .catch(() => {}); // worker gone: leave the layer as it is rather than flickering
    });
  } catch {
    // Extension reloaded under an open tab: no listener, the page just keeps what it has.
  }
}

async function main(): Promise<void> {
  console.log(`[parrot] running on ${location.hostname} · build ${BUILD}`);

  const blocked = neverListReason(location.href) ?? neverListPageReason(document);
  if (blocked) {
    console.log("[parrot] never-list, leaving this page alone:", blocked);
    return;
  }
  if (!document.body) return;

  articleKey = await computeArticleKey();
  await loadBudget();
  // Registered before the early return, so switching Luci ON mid-page lights the layer too.
  watchLuciSwitch();
  if (pageCap === 0) {
    console.log("[parrot] swaps set to 0 for this page");
    return;
  }
  showAmbience();
  injectStyle();
  wireHoverCard();
  observeForSeen = watchSeen((lemma) => queue(newEvent("seen", { lemma })));
  watchForNewText();

  // One reading event per page: title and domain only, never the URL (specs §5.1).
  queue(newEvent("reading", { meta: { title: document.title, domain: location.hostname } }));

  for (const delay of SWEEP_DELAYS_MS) {
    setTimeout(() => {
      void sweep(document.body).catch((err: unknown) => {
        console.error(`[parrot] sweep@${delay}ms failed:`, err);
      });
    }, delay);
  }
}

if (alreadyLoaded) {
  console.log("[parrot] already running in this tab, second injection ignored");
} else {
  void main().catch((err: unknown) => console.error("[parrot] startup failed:", err));
}
