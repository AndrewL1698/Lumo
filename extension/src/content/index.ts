/** Replace `span` inside one text node. Never spans elements (architecture §6.6). */
function applySwap(m: Match, span: string, replacement: string): boolean {
  const text = m.node.nodeValue;
  if (!text) return false;
  const start = text.indexOf(span);
  if (start < 0) return false; // span crosses an inline element: skip rather than guess

  const tail = m.node.splitText(start);
  tail.nodeValue = tail.nodeValue!.slice(span.length);

  const el = document.createElement("span");
  el.setAttribute(MARK_ATTR, "");
  el.dataset.parrotEn = span;
  el.dataset.parrotLemma = m.lemma;
  el.dataset.parrotGlow = m.glow;
  el.dataset.parrotSentence = m.sentence;
  el.textContent = replacement;
  m.node.parentNode?.insertBefore(el, tail);

  swapCount++;
  swappedLemmas.add(m.lemma);
  lastSwapWordIndex = m.wordIndex;
  observeForSeen?.(el);
  return true;
}

/**
 * One replacement inside one text node: [start, end) of its current text becomes `el`. Generic so whole Spanish
 * sentences (Part B, D-018) can go through the same applier; a higher `rank` wins an overlap (blocks over words).
 */
interface SwapOp {
  node: Text;
  start: number;
  end: number;
  el: HTMLElement;
  rank: number;
  /** The node's text over [start, end) when the op was made; if the page rewrote it meanwhile, the op is skipped. */
  expect: string;
  /** Bookkeeping, run once the element is in the page. */
  onApplied: () => void;
}

/**
 * Where the server's `span` sits in the node: the occurrence that contains the matched token. The server may
 * widen the span (a determiner, "the company"), so search from just before the token. -1 = not in this node.
 */
function locateSpan(m: Match, span: string): number {
  const text = m.node.nodeValue ?? "";
  if (!span) return -1;
  const tokenEnd = m.offset + m.englishMatch.length;
  for (let s = text.indexOf(span, Math.max(0, m.offset - span.length)); s >= 0 && s <= m.offset; s = text.indexOf(span, s + 1)) {
    if (s + span.length >= tokenEnd) return s;
  }
  return -1;
}

function wordOp(m: Match, start: number, span: string, replacement: string): SwapOp {
  // Same element and bookkeeping as applySwap().
  const el = document.createElement("span");
  el.setAttribute(MARK_ATTR, "");
  el.dataset.parrotEn = span;
  el.dataset.parrotLemma = m.lemma;
  el.dataset.parrotGlow = m.glow;
  el.dataset.parrotSentence = m.sentence;
  el.textContent = replacement;
  return {
    node: m.node,
    start,
    end: start + span.length,
    expect: span,
    el,
    rank: 0,
    onApplied() {
      swapCount++;
      swappedLemmas.add(m.lemma);
      lastSwapWordIndex = Math.max(lastSwapWordIndex, m.wordIndex);
      observeForSeen?.(el);
    },
  };
}

/**
 * Apply many replacements, several per text node. Overlaps are dropped (higher rank first, then earlier start).
 * Each node is cut from its end backwards, so the earlier offsets stay valid. Returns how many were applied.
 */
function applyOps(ops: SwapOp[]): number {
  const byNode = new Map<Text, SwapOp[]>();
  for (const op of [...ops].sort((a, b) => b.rank - a.rank || a.start - b.start)) {
    const kept = byNode.get(op.node) ?? [];
    if (kept.some((k) => op.start < k.end && k.start < op.end)) continue;
    kept.push(op);
    byNode.set(op.node, kept);
  }

  let applied = 0;
  for (const [node, kept] of byNode) {
    if (!node.parentNode) continue;
    for (const op of kept.sort((a, b) => b.start - a.start)) {
      if (op.end > node.length) continue;
      if (node.data.slice(op.start, op.end) !== op.expect) continue; // the page changed this text meanwhile
      const after = node.splitText(op.end);
      seenNodes.add(after); // our own split: the MutationObserver's re-sweep must not reprocess it
      const mid = node.splitText(op.start);
      mid.replaceWith(op.el);
      op.onApplied();
      applied++;
    }
  }
  return applied;
}

// ---------------------------------------------------------------- whole sentences and paragraphs (D-018 Part B)

/** A range of one text node to turn into Spanish as a whole. */
interface Block {
  kind: "sentence" | "paragraph";
  node: Text;
  start: number;
  end: number;
  /** The original English, whitespace collapsed: what we send and what the hover card shows. */
  english: string;
  /** The node's exact text over [start, end), checked again just before applying. */
  raw: string;
  /** Share of its words the learner knows or is learning (best lemma), then share in the word list. */
  known: number;
  inForms: number;
}

const WORD_RE = /[A-Za-z][A-Za-z'’-]*/g;

/** Shrink [start, end) so it neither starts nor ends with whitespace. */
function trimRange(text: string, start: number, end: number): [number, number] {
  while (start < end && /\s/.test(text[start] ?? "")) start++;
  while (end > start && /\s/.test(text[end - 1] ?? "")) end--;
  return [start, end];
}

/** Word count, and the shares in the word list and known-ish (by each word's best lemma). */
function blockStats(text: string, byLemma: Map<string, Candidate>): { words: number; inForms: number; known: number } {
  let words = 0;
  let inForms = 0;
  let known = 0;
  for (const m of text.matchAll(WORD_RE)) {
    words++;
    const lemmas = FORMS[m[0].toLowerCase()];
    if (!lemmas?.length) continue;
    inForms++;
    let best = lemmas[0]!;
    let bestScore = -Infinity;
    for (const l of lemmas) {
      const s = scoreOf(byLemma.get(l), l);
      if (s > bestScore) [best, bestScore] = [l, s];
    }
    if (KNOWNISH.has(byLemma.get(best)?.state ?? "")) known++;
  }
  return { words, inForms: words ? inForms / words : 0, known: words ? known / words : 0 };
}

/** The block for [from, to) of `node` (trimmed), and its word count. */
function makeBlock(
  kind: Block["kind"],
  node: Text,
  from: number,
  to: number,
  byLemma: Map<string, Candidate>,
): [Block, number] {
  const text = node.nodeValue ?? "";
  const [start, end] = trimRange(text, from, to);
  const raw = text.slice(start, end);
  const english = raw.replace(/\s+/g, " ");
  const { words, inForms, known } = blockStats(english, byLemma);
  return [{ kind, node, start, end, english, raw, known, inForms }, words];
}

const byBlockScore = (a: Block, b: Block) => b.known - a.known || b.inForms - a.inForms;

/**
 * Paragraphs first (a plain <p> that is exactly one text node, ≥25 words, in article/main when the page has one),
 * then single complete sentences from the other nodes (6–60 words, ≥40% in the word list, one per node). Only
 * `nodes` (new, visible, not skipped) are considered.
 */
function pickBlocks(nodes: Text[], byLemma: Map<string, Candidate>): Block[] {
  const wantParagraphs = Math.max(0, rules.paragraphBlocks - paragraphBlocksDone);
  const wantSentences = Math.max(0, rules.sentenceBlocks - sentenceBlocksDone);
  if (!wantParagraphs && !wantSentences) return [];
  const hasMain = Boolean(document.querySelector("article, main"));

  const paragraphs: Block[] = [];
  if (wantParagraphs) {
    for (const node of nodes) {
      const p = node.parentElement;
      if (p?.tagName !== "P" || p.childNodes.length !== 1) continue;
      if (p.closest(BLOCK_SKIP) || (hasMain && !p.closest("article, main"))) continue;
      const [block, words] = makeBlock("paragraph", node, 0, node.length, byLemma);
      if (words >= 25) paragraphs.push(block);
    }
  }
  const pickedParagraphs = paragraphs.sort(byBlockScore).slice(0, wantParagraphs);
  const inParagraph = new Set(pickedParagraphs.map((b) => b.node));

  const sentences: Block[] = [];
  if (wantSentences) {
    for (const node of nodes) {
      if (inParagraph.has(node) || node.parentElement?.closest(BLOCK_SKIP)) continue;
      const text = node.nodeValue ?? "";
      // Complete inside this node: starts at a boundary (or the node start with nothing before it in the
      // element), ends at a terminator (or the node end with nothing after it).
      const bounds: [number, number][] = [];
      let from = 0;
      for (const t of text.matchAll(/[.!?]+(?=\s|$)/g)) {
        const to = t.index + t[0].length;
        if (from > 0 || !node.previousSibling) bounds.push([from, to]);
        from = to;
      }
      if (from < text.length && (from > 0 || !node.previousSibling) && !node.nextSibling) bounds.push([from, text.length]);

      let best: Block | undefined;
      for (const [a, b] of bounds) {
        const [block, words] = makeBlock("sentence", node, a, b, byLemma);
        if (words < 6 || words > 60 || block.inForms < 0.4) continue;
        if (!best || byBlockScore(block, best) < 0) best = block;
      }
      if (best) sentences.push(best);
    }
  }
  return [...pickedParagraphs, ...sentences.sort(byBlockScore).slice(0, wantSentences)];
}

function blockOp(b: Block, spanish: string): SwapOp {
  const el = document.createElement("span");
  el.setAttribute(BLOCK_ATTR, "");
  el.dataset.parrotEn = b.english;
  el.textContent = spanish;
  return {
    node: b.node,
    start: b.start,
    end: b.end,
    expect: b.raw,
    el,
    rank: 1, // a block wins over any word swap inside it
    onApplied() {
      if (b.kind === "paragraph") paragraphBlocksDone++;
      else sentenceBlocksDone++;
    },
  };
}

/** Immersion steps 1–3 (D-018): many swaps per text node, placed by offset. Step 0 never comes here. */
async function sweepImmersive(root: Node): Promise<void> {
  const blocksLeft =
    sentenceBlocksDone < rules.sentenceBlocks || paragraphBlocksDone < rules.paragraphBlocks;
  if (swapCount >= pageCap && !blocksLeft) return;

  const nodes = collectTextNodes(root).filter((n) => !seenNodes.has(n));
  for (const n of nodes) seenNodes.add(n);
  if (!nodes.length) return;

  const candidates = await send({ type: "GET_CANDIDATES" }).catch(() => null);
  const byLemma = new Map((candidates?.candidates ?? []).map((c) => [c.lemma, c]));

  // Blocks are reserved before word picking: paragraph nodes leave the word pass, and words inside a chosen
  // sentence are not picked.
  const blocks = blocksLeft ? pickBlocks(nodes, byLemma) : [];
  const paragraphNodes = new Set(blocks.filter((b) => b.kind === "paragraph").map((b) => b.node));
  const sentenceRanges = new Map(blocks.filter((b) => b.kind === "sentence").map((b) => [b.node, b]));
  const matches = findMatches(
    nodes.filter((n) => !paragraphNodes.has(n)),
    byLemma,
  ).filter((m) => {
    const r = sentenceRanges.get(m.node);
    return !r || m.offset + m.englishMatch.length <= r.start || m.offset >= r.end;
  });
  const chosen = selectImmersive(matches, Math.max(0, pageCap - swapCount));
  if (!chosen.length && !blocks.length) {
    console.log(`[parrot] step ${rules.step}: ${nodes.length} new text node(s), nothing worth swapping`);
    return;
  }

  // ONE word batch plus ONE sentence batch, in parallel. Swaps appear only after they return; load is never blocked.
  const [res, blockRes] = await Promise.all([
    chosen.length
      ? send({
          type: "TRANSLATE",
          articleKey,
          items: chosen.map((m) => ({ sentence: m.sentence, lemma: m.lemma, englishMatch: m.englishMatch })),
        }).catch(() => null)
      : null,
    blocks.length
      ? send({ type: "TRANSLATE_SENTENCES", articleKey, sentences: blocks.map((b) => b.english) }).catch(() => null)
      : null,
  ]);

  if (chosen.length && !res) console.log("[parrot] translate unavailable, no word swaps this time");
  if (blocks.length && !blockRes) console.log("[parrot] sentence translate unavailable, no blocks this time");

  const ops: SwapOp[] = [];
  res?.items.forEach((item, i) => {
    const m = chosen[i];
    if (!item || !m) return; // null = sense mismatch, don't swap
    if (swappedLemmas.has(m.lemma)) return; // another sweep swapped it while this batch was out
    const start = locateSpan(m, item.span);
    if (start < 0) return; // span not in this node (crosses an inline element): skip rather than guess
    ops.push(wordOp(m, start, item.span, item.replacement));
  });
  ops.splice(Math.max(0, pageCap - swapCount)); // a parallel sweep may have used some of the budget
  const wordOps = ops.length;
  blockRes?.items.forEach((spanish, i) => {
    const b = blocks[i];
    if (spanish && b) ops.push(blockOp(b, spanish)); // null = leave that text English
  });

  const [sBefore, pBefore] = [sentenceBlocksDone, paragraphBlocksDone];
  const applied = applyOps(ops);
  const blocksApplied = sentenceBlocksDone - sBefore + paragraphBlocksDone - pBefore;
  console.log(
    `[parrot] step ${rules.step}: swapped ${applied - blocksApplied} of ${chosen.length} chosen ` +
      `(${wordOps} translated, page total ${swapCount}), ≤${rules.perSentence} per sentence`,
  );
  if (blocks.length) {
    console.log(
      `[parrot] blocks: ${sentenceBlocksDone - sBefore} sentences + ${paragraphBlocksDone - pBefore} paragraphs ` +
        `applied of ${blocks.length} chosen`,
    );
  }
}

async function sweep(root: Node): Promise<void> {
  if (rules.step > 0) return sweepImmersive(root);
  if (swapCount >= pageCap) return;

  const nodes = collectTextNodes(root).filter((n) => !seenNodes.has(n));
  for (const n of nodes) seenNodes.add(n);
  if (!nodes.length) return;

  const candidates = await send({ type: "GET_CANDIDATES" }).catch(() => null);
  const byLemma = new Map((candidates?.candidates ?? []).map((c) => [c.lemma, c]));

  const matches = findMatches(nodes, byLemma);
  const chosen = select(matches, pageCap - swapCount);
  if (!chosen.length) {
    console.log(`[parrot] ${nodes.length} new text node(s), nothing worth swapping`);
    return;
  }

  // ONE batch for the page. Swaps appear only after it returns; load is never blocked.
  const res = await send({
    type: "TRANSLATE",
    articleKey,
    items: chosen.map((m) => ({
      sentence: m.sentence,
      lemma: m.lemma,
      englishMatch: m.englishMatch,
    })),
  }).catch(() => null);

  if (!res) {
    console.log("[parrot] translate unavailable, leaving the page alone");
    return;
  }

  let applied = 0;
  res.items.forEach((item, i) => {
    const m = chosen[i];
    if (!item || !m) return; // null = sense mismatch, don't swap
    if (swapCount >= pageCap) return;
    if (applySwap(m, item.span, item.replacement)) applied++;
  });
  console.log(`[parrot] swapped ${applied} of ${chosen.length} (page total ${swapCount})`);
}

// ---------------------------------------------------------------- observers

let timer: ReturnType<typeof setTimeout> | undefined;
function watchForNewText(): void {
  const observer = new MutationObserver((records) => {
    if (swapCount >= pageCap) {
      observer.disconnect();
      return;
    }
    const roots = records
      .flatMap((r) => [...r.addedNodes])
      .filter((n) => n.nodeType === Node.ELEMENT_NODE || n.nodeType === Node.TEXT_NODE);
    if (!roots.length) return;

    clearTimeout(timer);
    timer = setTimeout(() => {
      if (neverListReason(location.href)) {
        observer.disconnect();
        return;
      }
      for (const root of roots) if (root.isConnected) void sweep(root);
    }, DEBOUNCE_MS);
  });
  observer.observe(document.body, { childList: true, subtree: true });
}

function wireHoverCard(): void {
  installHoverCard(MARK_ATTR, {
    onHover(t: HoverTarget) {
      queue(newEvent("hover", { lemma: t.lemma, meta: { sentence: t.sentence } }));
      // A look-up makes the word "learning" (learner model), so it starts to flicker right away.
      for (const el of document.querySelectorAll<HTMLElement>(`[${MARK_ATTR}]`)) {
        if (el.dataset.parrotLemma === t.lemma && el.dataset.parrotGlow === "seen") el.dataset.parrotGlow = "learning";
      }
    },
    onVerdict(t: HoverTarget, verdict) {
      queue(newEvent(verdict, { lemma: t.lemma, meta: { sentence: t.sentence } }));
      // D-018, display only: Knew it = steady (no flicker), Didn't know = flicker. Solid stays for proven-known.
      if (verdict === "knew_it") knewIt.add(t.lemma);
      else knewIt.delete(t.lemma);
      for (const el of document.querySelectorAll<HTMLElement>(`[${MARK_ATTR}]`)) {
        if (el.dataset.parrotLemma !== t.lemma || el.dataset.parrotGlow === "known") continue;
        el.dataset.parrotGlow = verdict === "knew_it" ? "steady" : "learning";
      }
    },
    /** The service worker fetches and caches the audio; we only play it. */
    async onSpeak(t: HoverTarget) {
      const res = await send({ type: "TTS", text: t.spanish, lemma: t.lemma }).catch(() => null);
      if (!res) return false;
      try {
        await new Audio(res.dataUrl).play();
        return true;
      } catch (err) {
        // Some pages' CSP blocks media from a data: URL.
        // TODO(naren): fall back to an offscreen document if a demo site does this.
        console.warn("[parrot] could not play pronunciation here", err);
        return false;
      }
    },
  });
}

/** Swap amount (popup slider or "Grow automatically") and the learner's level, from Settings + progress. */
async function loadBudget(): Promise<void> {
  const [s, c] = await Promise.all([
    send({ type: "GET_SETTINGS" }).catch(() => null),
    send({ type: "GET_CANDIDATES" }).catch(() => null),
  ]);
  if (!s) return; // service worker unreachable: keep the defaults
  // An older service worker sends no immersion: that's step 0, today's behaviour.
  const immersion = s.immersion ?? { points: 0, rate: 1, percent: 0 };
  rules = pageRules(s.settings, s.autoGrow, immersion, c?.candidates ?? []);
  pageCap = rules.words;
  userBand = LEVEL_BAND[s.settings.level] ?? 2;
  minGap = rules.step === 0 ? Math.max(4, Math.round((MIN_WORD_GAP * 10) / Math.max(10, pageCap))) : rules.minGap;
  for (const lemma of s.knewIt ?? []) knewIt.add(lemma);
  console.log(
    `[parrot] step ${rules.step}, immersion ${immersion.percent}%, budget ${pageCap} swaps ` +
      `(${s.autoGrow ? "auto" : "slider"}), ≤${rules.perSentence} per sentence, gap ${minGap}, level ${s.settings.level}`,
  );
}

async function main(): Promise<void> {
  console.log(`[parrot] running on ${location.hostname} · build ${BUILD}`);

  const blocked = neverListReason(location.href) ?? neverListPageReason(document);
  if (blocked) {
    console.log("[parrot] never-list, leaving this page alone:", blocked);
    return;
  }
  if (!document.body) return;

  articleKey = await computeArticleKey();
  await loadBudget();
  if (pageCap === 0) {
    console.log("[parrot] swaps set to 0 for this page");
    return;
  }
  injectStyle();
  wireHoverCard();
  observeForSeen = watchSeen((lemma) => queue(newEvent("seen", { lemma })));
  watchForNewText();

  // One reading event per page: title and domain only, never the URL (specs §5.1).
  queue(newEvent("reading", { meta: { title: document.title, domain: location.hostname } }));

  for (const delay of SWEEP_DELAYS_MS) {
    setTimeout(() => {
      void sweep(document.body).catch((err: unknown) => {
        console.error(`[parrot] sweep@${delay}ms failed:`, err);
      });
    }, delay);
  }
}

void main().catch((err: unknown) => console.error("[parrot] startup failed:", err));
