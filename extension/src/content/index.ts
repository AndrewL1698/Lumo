/**
 * One replacement inside one text node: [start, end) of its current text becomes `el`. Generic so whole Spanish
 * sentences (Part B, D-018) can go through the same applier; a higher `rank` wins an overlap (blocks over words).
 */
interface SwapOp {
  node: Text;
  start: number;
  end: number;
  el: HTMLElement;
  rank: number;
  /** The node's text over [start, end) when the op was made; if the page rewrote it meanwhile, the op is skipped. */
  expect: string;
  /** Bookkeeping, run once the element is in the page. */
  onApplied: () => void;
}

/**
 * Where the server's `span` sits in the node: the occurrence that contains the matched token. The server may
 * widen the span (a determiner, "the company"), so search from just before the token. -1 = not in this node.
 */
function locateSpan(m: Match, span: string, text = m.node.nodeValue ?? ""): number {
  if (!span) return -1;
  const tokenEnd = m.offset + m.englishMatch.length;
  for (let s = text.indexOf(span, Math.max(0, m.offset - span.length)); s >= 0 && s <= m.offset; s = text.indexOf(span, s + 1)) {
    if (s + span.length >= tokenEnd) return s;
  }
  return -1;
}

function wordOp(m: Match, start: number, span: string, replacement: string): SwapOp {
  const el = document.createElement("span");
  el.setAttribute(MARK_ATTR, "");
  el.dataset.parrotEn = span;
  el.dataset.parrotLemma = m.lemma;
  el.dataset.parrotGlow = m.glow;
  el.dataset.parrotSentence = m.sentence;
  el.textContent = replacement;
  return {
    node: m.node,
    start,
    end: start + span.length,
    expect: span,
    el,
    rank: 0,
    onApplied() {
      swapCount++;
      swappedLemmas.add(m.lemma);
      observeForSeen?.(el);
    },
  };
}

/**
 * An original text node's pieces left after our splits, each with its offset in the original text. Op offsets are
 * always in original-node coordinates, so word and block batches can land in any order (D-018 Part B).
 */
const pieces = new WeakMap<Text, { node: Text; at: number }[]>();

/**
 * Apply many replacements, several per text node. Overlaps are dropped (higher rank first, then earlier start).
 * Each op is cut out of whichever piece of its original node still holds its range. Returns how many were applied.
 */
function applyOps(ops: SwapOp[]): number {
  const byNode = new Map<Text, SwapOp[]>();
  for (const op of [...ops].sort((a, b) => b.rank - a.rank || a.start - b.start)) {
    const kept = byNode.get(op.node) ?? [];
    if (kept.some((k) => op.start < k.end && k.start < op.end)) continue;
    kept.push(op);
    byNode.set(op.node, kept);
  }

  let applied = 0;
  for (const [origin, kept] of byNode) {
    const list = pieces.get(origin) ?? [{ node: origin, at: 0 }];
    pieces.set(origin, list);
    for (const op of kept.sort((a, b) => b.start - a.start)) {
      const piece = list.find((p) => op.start >= p.at && op.end <= p.at + p.node.length);
      if (!piece?.node.parentNode) continue;
      const [start, end] = [op.start - piece.at, op.end - piece.at];
      if (piece.node.data.slice(start, end) !== op.expect) continue; // the page changed this text meanwhile
      const after = piece.node.splitText(end);
      seenNodes.add(after); // our own split: the MutationObserver's re-sweep must not reprocess it
      list.push({ node: after, at: op.end });
      const mid = piece.node.splitText(start);
      mid.replaceWith(op.el);
      op.onApplied();
      applied++;
    }
  }
  return applied;
}

// ---------------------------------------------------------------- whole sentences and paragraphs (D-018 Part B)

/** A range of one text node to turn into Spanish as a whole. */
interface Block {
  kind: "sentence" | "paragraph";
  node: Text;
  start: number;
  end: number;
  /** The original English, whitespace collapsed: what we send and what the hover card shows. */
  english: string;
  /** The node's exact text over [start, end), checked again just before applying. */
  raw: string;
  /** Share of its words the learner knows or is learning (best lemma), then share in the word list. */
  known: number;
  inForms: number;
}

const WORD_RE = /[A-Za-z][A-Za-z'’-]*/g;

/** Shrink [start, end) so it neither starts nor ends with whitespace. */
function trimRange(text: string, start: number, end: number): [number, number] {
  while (start < end && /\s/.test(text[start] ?? "")) start++;
  while (end > start && /\s/.test(text[end - 1] ?? "")) end--;
  return [start, end];
}

/** Word count, and the shares in the word list and known-ish (by each word's best lemma). */
function blockStats(text: string, byLemma: Map<string, Candidate>): { words: number; inForms: number; known: number } {
  let words = 0;
  let inForms = 0;
  let known = 0;
  for (const m of text.matchAll(WORD_RE)) {
    words++;
    const lemmas = FORMS[m[0].toLowerCase()];
    if (!lemmas?.length) continue;
    inForms++;
    let best = lemmas[0]!;
    let bestScore = -Infinity;
    for (const l of lemmas) {
      const s = scoreOf(byLemma.get(l), l);
      if (s > bestScore) [best, bestScore] = [l, s];
    }
    if (KNOWNISH.has(byLemma.get(best)?.state ?? "")) known++;
  }
  return { words, inForms: words ? inForms / words : 0, known: words ? known / words : 0 };
}

/** The block for [from, to) of `node` (trimmed), and its word count. */
function makeBlock(
  kind: Block["kind"],
  node: Text,
  from: number,
  to: number,
  byLemma: Map<string, Candidate>,
): [Block, number] {
  const text = node.nodeValue ?? "";
  const [start, end] = trimRange(text, from, to);
  const raw = text.slice(start, end);
  const english = raw.replace(/\s+/g, " ");
  const { words, inForms, known } = blockStats(english, byLemma);
  return [{ kind, node, start, end, english, raw, known, inForms }, words];
}

const byBlockScore = (a: Block, b: Block) => b.known - a.known || b.inForms - a.inForms;

/**
 * Paragraphs first (a plain <p> that is exactly one text node, ≥25 words, in article/main when the page has one),
 * then single complete sentences from the other nodes (6–60 words, ≥40% in the word list, one per node). Only
 * `nodes` (new, visible, not skipped) are considered.
 */
function pickBlocks(nodes: Text[], byLemma: Map<string, Candidate>): Block[] {
  const wantParagraphs = Math.max(0, rules.paragraphBlocks - paragraphBlocksDone);
  const wantSentences = Math.max(0, rules.sentenceBlocks - sentenceBlocksDone);
  if (!wantParagraphs && !wantSentences) return [];
  const hasMain = Boolean(document.querySelector("article, main"));
  /** Body text only: a <p> (so not an <em> inside one), in article/main when the page has one, no boilerplate. */
  const bodyP = (el: Element | null): el is Element =>
    el?.tagName === "P" &&
    !el.closest(BLOCK_SKIP) &&
    (!hasMain || Boolean(el.closest("article, main"))) &&
    !inBoilerplate(el);

  const paragraphs: Block[] = [];
  if (wantParagraphs) {
    for (const node of nodes) {
      const p = node.parentElement;
      if (!bodyP(p) || p.childNodes.length !== 1) continue;
      const [block, words] = makeBlock("paragraph", node, 0, node.length, byLemma);
      if (words >= 25) paragraphs.push(block);
    }
  }
  const pickedParagraphs = paragraphs.sort(byBlockScore).slice(0, wantParagraphs);
  const inParagraph = new Set(pickedParagraphs.map((b) => b.node));

  const sentences: Block[] = [];
  if (wantSentences) {
    for (const node of nodes) {
      if (inParagraph.has(node) || !bodyP(node.parentElement)) continue;
      let best: Block | undefined;
      for (const [a, b] of sentenceBounds(node.data, !node.previousSibling, !node.nextSibling)) {
        const [block, words] = makeBlock("sentence", node, a, b, byLemma);
        if (words < 6 || words > 60 || block.inForms < 0.4 || !quotesBalanced(block.english)) continue;
        if (!best || byBlockScore(block, best) < 0) best = block;
      }
      if (best) sentences.push(best);
    }
  }
  const pickedSentences = sentences.sort(byBlockScore).slice(0, wantSentences);
  // Counted when picked, so an overlapping sweep can't pick a second set while this one's translation is out.
  paragraphBlocksDone += pickedParagraphs.length;
  sentenceBlocksDone += pickedSentences.length;
  return [...pickedParagraphs, ...pickedSentences];
}

const BOILERPLATE = /caption|credit|byline|promo|newsletter|cookie|banner/i;
function inBoilerplate(el: Element): boolean {
  for (let e: Element | null = el; e && e !== document.body; e = e.parentElement) {
    if (BOILERPLATE.test(e.getAttribute("class") ?? "")) return true;
  }
  return false;
}

